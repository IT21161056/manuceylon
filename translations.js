/**
 * i18n Application Controller
 */
const AppI18n = {
  currentLang: 'en',

  init() {
    // Load persisted language or default to 'en'
    let saved = null;
    try {
      if (typeof localStorage !== 'undefined') {
        saved = localStorage.getItem('manuceylon_lang');
      }
    } catch (e) {
      // Storage restricted / sandbox mode
    }

    if (saved === 'si' || saved === 'en') {
      this.currentLang = saved;
    } else {
      this.currentLang = 'en';
    }

    this.applyLanguage(this.currentLang);
    this.bindEvents();
  },

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'si') return;
    this.currentLang = lang;
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('manuceylon_lang', lang);
      }
    } catch (e) {
      // Storage restricted
    }
    this.applyLanguage(lang);

    // Dispatch event for other modules
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    }
  },

  getLanguage() {
    return this.currentLang;
  },

  t(key) {
    const dict = translations[this.currentLang] || translations.en;
    return dict[key] || translations.en[key] || key;
  },

  applyLanguage(lang) {
    if (typeof document === 'undefined') return;
    // Set document lang attribute
    document.documentElement.lang = lang;

    const dict = translations[lang] || translations.en;

    // Update document title and meta description
    if (dict['meta.title']) document.title = dict['meta.title'];
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && dict['meta.description']) {
      metaDesc.setAttribute('content', dict['meta.description']);
    }

    // 1. Text elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.textContent = dict[key];
      }
    });

    // 2. HTML elements with data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    // 3. Placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] !== undefined) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // 4. Aria labels with data-i18n-aria
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      if (dict[key] !== undefined) {
        el.setAttribute('aria-label', dict[key]);
      }
    });

    // 5. Update Treatment Cards
    this.updateTreatments(lang);

    // 6. Update Product Cards
    this.updateProductCards(lang);

    // 7. Update Switcher active states
    this.updateSwitcherButtons(lang);

    // 8. Update Clinic Live Status if defined
    if (typeof window !== 'undefined' && typeof window.initClinicStatus === 'function') {
      window.initClinicStatus();
    }
  },

  updateTreatments(lang) {
    const tData = treatmentsI18n[lang] || treatmentsI18n.en;
    const cards = document.querySelectorAll('.treatment-card');
    const keys = ['joint', 'gynecology', 'ncds', 'hemorrhoids', 'skin', 'acupuncture'];

    cards.forEach((card, index) => {
      const key = keys[index];
      const data = tData[key];
      if (!data) return;

      const badge = card.querySelector('.treatment-sinhala-badge');
      if (badge) badge.textContent = data.badge;

      const title = card.querySelector('.treatment-en-title');
      if (title) title.textContent = data.title;

      const desc = card.querySelector('.treatment-desc');
      if (desc) desc.textContent = data.desc;
    });
  },

  updateProductCards(lang) {
    const pData = productsI18n[lang] || productsI18n.en;
    const cards = document.querySelectorAll('.product-card');

    cards.forEach(card => {
      const btn = card.querySelector('.btn-quick-view');
      const productId = btn ? btn.dataset.productId : null;
      if (!productId || !pData[productId]) return;

      const item = pData[productId];

      const tag = card.querySelector('.product-tag');
      if (tag) {
        const tagKey = `products.tag.${item.category}`;
        tag.textContent = this.t(tagKey) || item.categoryName;
      }

      const title = card.querySelector('.product-title');
      if (title) title.textContent = item.title;

      const subtitle = card.querySelector('.product-subtitle');
      if (subtitle) subtitle.textContent = item.subtitle;

      const desc = card.querySelector('.product-desc');
      if (desc) desc.textContent = item.desc;
    });
  },

  updateSwitcherButtons(lang) {
    document.querySelectorAll('.lang-btn, .drawer-lang-btn, .top-lang-btn').forEach(btn => {
      if (btn.dataset.lang === lang) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });
  },

  bindEvents() {
    if (typeof document !== 'undefined') {
      document.addEventListener('click', (e) => {
        const btn = e.target.closest('.lang-btn, .drawer-lang-btn, .top-lang-btn');
        if (btn && btn.dataset.lang) {
          e.preventDefault();
          this.setLanguage(btn.dataset.lang);
        }
      });
    }
  }
};

